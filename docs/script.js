const f1 = (v) => v.toFixed(1).replace(".", ",");
function imputed(a) {
    const z = (a || y).slice();
    closed.forEach((i) => {
        let j = i - 7;
        while (j >= 0 && closed.has(j)) j -= 7;
        z[i] = z[j];
    });
    return z;
}
function forecast(z, h, P) {
    const m = 7;
    let l = 0;
    for (let i = 0; i < m; i++) l += z[i];
    l /= m;
    const s = [];
    for (let i = 0; i < m; i++) s[i] = z[i] - l;
    for (let t = m; t < z.length; t++) {
        const lp = l;
        l = P.a * (z[t] - s[t - m]) + (1 - P.a) * lp;
        s[t] = P.g * (z[t] - lp) + (1 - P.g) * s[t - m];
    }
    const n = z.length,
        f = [];
    for (let k = 1; k <= h; k++)
        f.push(Math.max(0, l + s[n - 7 + ((k - 1) % 7)]));
    return f;
}
function chart(f) {
    const n = y.length,
        W = 640,
        H = 250,
        L = 36,
        R = 12,
        T = 14,
        B = 30,
        N = 28 + 7;
    const act = y.slice(n - 28),
        all = act.concat(f.map((v) => v + P.mae));
    const mx = Math.ceil((Math.max.apply(null, all) + 2) / 5) * 5;
    const X = (i) => L + (i * (W - L - R)) / (N - 1),
        Y = (v) => T + (1 - v / mx) * (H - T - B);
    let g = "";
    for (let v = 0; v <= mx; v += mx / 5) {
        g += `<line x1="${L}" x2="${W - R}" y1="${Y(v)}" y2="${Y(v)}" stroke="var(--line)"/><text x="${L - 6}" y="${Y(v) + 4}" font-size="10" text-anchor="end" fill="var(--muted)">${Math.round(v)}</text>`;
    }
    const pa = act
        .map((v, i) => (i ? "L" : "M") + X(i) + "," + Y(v))
        .join("");
    const fp = [[27, act[27]]].concat(f.map((v, k) => [28 + k, v]));
    const pf = fp
        .map((p, i) => (i ? "L" : "M") + X(p[0]) + "," + Y(p[1]))
        .join("");
    const up = f.map((v, k) => X(28 + k) + "," + Y(v + P.mae)),
        lo = f
            .map((v, k) => X(28 + k) + "," + Y(Math.max(0, v - P.mae)))
            .reverse();
    let xl = "";
    for (let i = 0; i < N; i += 7) {
        const idx = n - 28 + i;
        xl += `<text x="${X(i)}" y="${H - 8}" font-size="10" text-anchor="middle" fill="var(--muted)">${tgl(idx).getUTCDate()} ${BLN[tgl(idx).getUTCMonth()]}</text>`;
    }
    $("chart").innerHTML =
        g +
        xl +
        `<polygon points="${up.concat(lo).join(" ")}" fill="var(--band)"/>` +
        `<line x1="${X(27.5)}" x2="${X(27.5)}" y1="${T}" y2="${H - B}" stroke="var(--muted)" stroke-dasharray="3 3"/>` +
        `<path d="${pa}" fill="none" stroke="var(--pri)" stroke-width="2.5"/>` +
        `<path d="${pf}" fill="none" stroke="var(--acc)" stroke-width="2.5" stroke-dasharray="6 4"/>` +
        f
            .map(
                (v, k) =>
                    `<circle cx="${X(28 + k)}" cy="${Y(v)}" r="4" fill="var(--acc)"><title>${fmt(y.length + k)}: ${f1(v)}</title></circle>`,
            )
            .join("");
}
function weekend(fk, tetap, kst, kset) {
    const n = y.length;
    let i = 0;
    while (dow(n + i) !== 4) i++;
    const W = fk[i] + fk[i + 1],
        Wu = W + 2 * Q.mae,
        C = tetap * 2 * kst,
        fr = Math.ceil(Math.max(0, Wu - C) / kset);
    $("wk").innerHTML =
        `<p><b>Akhir Pekan (Sabtu ${fmt(n + i + 1)}):</b> Beban kerja tertunda (Jumat + Sabtu) ≈ <b>${Math.round(W)} kg</b> (batas atas ${Math.round(Wu)} kg). <br/>Kapasitas tim saat ini: ${tetap} org × 2 hari × ${kst} kg = <b>${C} kg</b><br/>` +
        (fr
            ? `<span class="pill warn">Diperlukan tambahan ${fr} freelance gosok di hari Minggu</span>`
            : `<span class="pill ok">Karyawan tetap memadai</span>`) +
        `</p>`;
}
function render() {
    const n = y.length,
        f = forecast(imputed(), 7, P),
        fk = forecast(imputed(kg), 14, Q);
    const tetap = Math.max(0, +$("tetap").value || 0),
        kst = Math.max(1, +$("kst").value || 1),
        kset = Math.max(1, +$("kset").value || 1);
    let mxv = -1,
        mxk = 0,
        tot = 0,
        rows = "";
    f.forEach((v, k) => {
        tot += v;
        if (v > mxv) {
            mxv = v;
            mxk = k;
        }
        const kv = fk[k];

        rows += `<tr>
            <td class="font-medium text-slate-800"><span class="block text-xs font-normal text-slate-400 mb-0.5">${HARI[dow(n + k)]}</span>${fmt(n + k)}</td>
            <td class="font-semibold text-blue-600">${f1(v)}</td>
            <td><span class="inline-flex items-center px-2.5 py-0.5 rounded-md bg-slate-100 text-slate-700 font-medium">${Math.round(kv)} kg</span></td>
            <td class="text-slate-500">${Math.round(Math.max(0, kv - Q.mae))} - ${Math.round(kv + Q.mae)} kg</td>
          </tr>`;
    });
    $("tb").innerHTML = rows;
    weekend(fk, tetap, kst, kset);
    $("k1").textContent = HARI[dow(n + mxk)];
    $("k2").textContent = Math.round(tot);
    $("k3").textContent = fmt(n - 1);
    $("pa").textContent = P.a.toFixed(4).replace(".", ",");
    $("pg").textContent = P.g.toFixed(4).replace(".", ",");
    chart(f);
}
